create table if not exists public.bixo_en_or_state (
  id text primary key,
  state jsonb not null,
  revision bigint not null default 0,
  updated_at timestamptz not null default now(),
  updated_by text
);

alter table public.bixo_en_or_state
  add column if not exists revision bigint not null default 0,
  add column if not exists updated_by text;

create table if not exists public.bixo_en_or_state_history (
  id bigint generated by default as identity primary key,
  state_id text not null,
  revision bigint not null,
  state jsonb not null,
  created_at timestamptz not null default now(),
  created_by text,
  reason text
);

alter table public.bixo_en_or_state enable row level security;
alter table public.bixo_en_or_state_history enable row level security;

drop policy if exists "Public read bixo_en_or_state" on public.bixo_en_or_state;
