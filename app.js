function parseCsvLine(line) {
  const cells = [];
  let current = "";
  let quoted = false;

  for (let i = 0; i < line.length; i += 1) {
    const char = line[i];
    const next = line[i + 1];

    if (char === '"' && quoted && next === '"') {
      current += '"';
      i += 1;
    } else if (char === '"') {
      quoted = !quoted;
    } else if (char === "," && !quoted) {
      cells.push(current.trim());
      current = "";
    } else {
      current += char;
    }
  }

  cells.push(current.trim());
  return cells;
}

function parsePoints(value) {
  const match = String(value || "").match(/-?\d+/);
  return match ? Number(match[0]) : 0;
}

function parseChallenges(raw) {
  const sections = raw.split("\f");
  const parsed = [];

  sections.forEach((section) => {
    const lines = section.split(/\r?\n/).filter(Boolean);
    if (!lines.length) return;

    const header = parseCsvLine(lines[0]);
    const category = (header[1] || header[0] || "Desafios").trim();
    const hasOwner = header.some((cell) => /veteranos|voteranos|vets/i.test(cell));

    lines.slice(1).forEach((line) => {
      const cells = parseCsvLine(line);
      const rowId = cells[0] || String(parsed.length);
      let title = "";
      let owner = "";
      let points = 0;
      let description = "";

      if (category === "BRASIL" || category === "FRANÇA") {
        title = cells[1] || "Défi sem título";
        points = parsePoints(cells[2]);
        description = cells.slice(3).filter(Boolean).join(" ");
      } else if (category === "Bônus e Penalidades") {
        title = cells[1] || "Evento";
        points = parsePoints(cells[2]);
        description = cells.slice(3).filter(Boolean).join(" ");
      } else if (hasOwner) {
        owner = cells[1] || owner;
        title = cells[2] || cells[4] || `${owner || "Veterano"} - desafio ${rowId}`;
        points = parsePoints(cells[3] || cells[2]);
        description = cells.slice(4).filter(Boolean).join(" ");
      } else {
        title = cells[1] || "Défi sem título";
        points = parsePoints(cells[2]);
        description = cells.slice(3).filter(Boolean).join(" ");
      }

      if (!title && !description) return;

      parsed.push({
        id: `${slug(category)}-${rowId}-${slug(title).slice(0, 36)}`,
        category,
        owner,
        title,
        points,
        description,
      });
    });
  });

  return parsed;
}

function slug(value) {
  return String(value)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

